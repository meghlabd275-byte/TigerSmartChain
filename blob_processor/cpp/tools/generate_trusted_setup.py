#!/usr/bin/env python3
"""Convert the EIP-4844 trusted setup text form into C++ source.

The text form is what upstream c-kzg-4844 ships. Embedding the points as C++
arrays removes any runtime file dependency, so a node cannot start with a
missing or substituted setup.

Usage: generate_trusted_setup.py <trusted_setup.txt> <out.cpp> <out.hpp>
"""
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    src, out_cpp, out_hpp = sys.argv[1:4]

    with open(src) as handle:
        lines = [line.strip() for line in handle if line.strip()]

    num_g1 = int(lines[0])
    num_g2 = int(lines[1])
    body = lines[2:]
    expected = 2 * num_g1 + num_g2
    if len(body) != expected:
        raise SystemExit(
            f"trusted setup has {len(body)} points, expected {expected} "
            f"(2*{num_g1} G1 + {num_g2} G2)"
        )

    # The file order is fixed by c-kzg's loader: G1 Lagrange, then G2
    # monomial, then G1 monomial. Reading them in a different order would load
    # a valid-looking but wrong setup.
    g1_lagrange = body[:num_g1]
    g2_monomial = body[num_g1:num_g1 + num_g2]
    g1_monomial = body[num_g1 + num_g2:]

    # A wrong line length would silently shift every point after it.
    for name, points, expected_chars in (
        ("G1 Lagrange", g1_lagrange, 96),
        ("G2 monomial", g2_monomial, 192),
        ("G1 monomial", g1_monomial, 96),
    ):
        for index, point in enumerate(points):
            if len(point) != expected_chars:
                raise SystemExit(
                    f"{name} point {index} has {len(point)} hex digits, "
                    f"expected {expected_chars}"
                )

    def emit(name, points):
        data = bytes.fromhex("".join(points))
        rows = []
        for offset in range(0, len(data), 16):
            chunk = data[offset:offset + 16]
            rows.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
        return (f"const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"
                f"const size_t {name}_size = sizeof({name});\n")

    with open(out_cpp, "w") as handle:
        handle.write(
            "// Generated by tools/generate_trusted_setup.py. Do not edit by hand.\n"
            "//\n"
            "// Mainnet EIP-4844 trusted setup: G1 monomial, G1 Lagrange, G2 monomial.\n"
            "// Regenerate from upstream c-kzg-4844's src/trusted_setup.txt when\n"
            "// upgrading the vendored copy.\n\n"
            '#include "trusted_setup_data.hpp"\n\n'
            "namespace tigerchain {\nnamespace blob {\nnamespace detail {\n\n"
        )
        handle.write(emit("kG1Monomial", g1_monomial))
        handle.write("\n")
        handle.write(emit("kG1Lagrange", g1_lagrange))
        handle.write("\n")
        handle.write(emit("kG2Monomial", g2_monomial))
        handle.write("\n} // namespace detail\n} // namespace blob\n} // namespace tigerchain\n")

    with open(out_hpp, "w") as handle:
        handle.write(
            "// Generated by tools/generate_trusted_setup.py. Do not edit by hand.\n\n"
            "#ifndef TIGERCHAIN_TRUSTED_SETUP_DATA_HPP\n"
            "#define TIGERCHAIN_TRUSTED_SETUP_DATA_HPP\n\n"
            "#include <cstddef>\n\n"
            "namespace tigerchain {\nnamespace blob {\nnamespace detail {\n\n"
            "/// Number of G1 points in the setup (monomial and Lagrange forms each).\n"
            f"constexpr size_t kTrustedSetupNumG1 = {num_g1};\n"
            "/// Number of G2 points in the setup.\n"
            f"constexpr size_t kTrustedSetupNumG2 = {num_g2};\n\n"
            "extern const unsigned char kG1Monomial[];\n"
            "extern const unsigned char kG1Lagrange[];\n"
            "extern const unsigned char kG2Monomial[];\n"
            "extern const size_t kG1Monomial_size;\n"
            "extern const size_t kG1Lagrange_size;\n"
            "extern const size_t kG2Monomial_size;\n\n"
            "} // namespace detail\n} // namespace blob\n} // namespace tigerchain\n\n"
            "#endif // TIGERCHAIN_TRUSTED_SETUP_DATA_HPP\n"
        )
    print(f"wrote {out_cpp} and {out_hpp}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
